// znaki z ogonkami: litera bazowa + ozdobnik; acute i dot rysujemy nad literą, ogonek pod nią
const ACCENTS = {
  Ą: ['A', 'ogonek'], Ę: ['E', 'ogonek'], Ó: ['O', 'acute'], Ć: ['C', 'acute'], Ń: ['N', 'acute'], Ś: ['S', 'acute'], Ź: ['Z', 'acute'], Ż: ['Z', 'dot'],
  Ł: ['L', 'slash'],
};

function glyph5(ch) {
  const c = ch.toUpperCase();
  if (ACCENTS[c]) {
    const [base, kind] = ACCENTS[c];
    let rows = G5[base].slice();
    let top = 0;
    let bottom = 0;
    if (kind === 'acute') {
      rows = ['...#.', '..#..', ...rows];
      top = 2;
    } else if (kind === 'dot') {
      rows = ['..#..', '.....', ...rows];
      top = 2;
    } else if (kind === 'ogonek') {
      rows = [...rows, '....#', '...#.'];
      bottom = 2;
    } else if (kind === 'slash') {
      rows = ['#....', '#.#..', '##...', '#....', '#....', '#....', '#####'];
    }
    return { rows, top, bottom };
  }
  return { rows: G5[c] || G5['?'], top: 0, bottom: 0 };
}

